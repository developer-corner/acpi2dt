#include "dts_merger.h"

static int run_dtc_compile_check(const wchar_t* dtc_exe, const wchar_t* dts_path, const wchar_t* dtb_path) {
    if (wcslen(dtc_exe) == 0) return 0;
    wchar_t cmd[WOA_MAX_PATH * 3];
    STARTUPINFOW si;
    PROCESS_INFORMATION pi;
    ZeroMemory(&si, sizeof(si));
    ZeroMemory(&pi, sizeof(pi));
    si.cb = sizeof(si);

    _snwprintf(cmd, sizeof(cmd) / sizeof(cmd[0]),
        L"\"%s\" -I dts -O dtb -o \"%s\" \"%s\"", dtc_exe, dtb_path, dts_path);

    if (!CreateProcessW(NULL, cmd, NULL, NULL, FALSE, 0, NULL, NULL, &si, &pi)) {
        return -1;
    }
    WaitForSingleObject(pi.hProcess, 15000);
    DWORD exit_code = 1;
    GetExitCodeProcess(pi.hProcess, &exit_code);
    CloseHandle(pi.hProcess);
    CloseHandle(pi.hThread);
    return (int)exit_code;
}

int woa_merge_and_validate_dts(const woa_config_t* cfg) {
    wchar_t target_dts[WOA_MAX_PATH];
    wchar_t target_dtb[WOA_MAX_PATH];
    _snwprintf(target_dts, WOA_MAX_PATH, L"%s\\target-merged.dts", cfg->output_dir);
    _snwprintf(target_dtb, WOA_MAX_PATH, L"%s\\target-merged.dtb", cfg->output_dir);

    FILE* out = _wfopen(target_dts, L"wb");
    if (!out) return -1;

    fputs("// SPDX-License-Identifier: BSD-3-Clause\n", out);
    fputs("/*\n * Auto-synthesized seed DTS generated by WoA-DtsHarvester (Plain C17)\n", out);
    fputs(" * Load acpi/*.dsl, hardware_inventory.json, inf_collected/*.inf, and\n", out);
    fputs(" * Primary/Secondary .dts into WoA DTS Workbench for interactive review.\n */\n\n", out);

    if (wcslen(cfg->primary_dts) > 0) {
        FILE* prim = _wfopen(cfg->primary_dts, L"rb");
        if (prim) {
            char line[1024];
            while (fgets(line, sizeof(line), prim)) {
                fputs(line, out);
            }
            fclose(prim);
            printf("[DTS] Copied Primary DTS seed into target-merged.dts\n");
        }
    } else {
        fputs("/dts-v1/;\n\n/ {\n\tmodel = \"Windows 11 ARM64 Target (Needs Review)\";\n\tcompatible = \"qcom,x1e80100\";\n};\n", out);
    }

    if (wcslen(cfg->secondary_dts) > 0) {
        fputs("\n/* === SECONDARY REFERENCE DTS APPENDIX (HUMAN REVIEW) === */\n/*\n", out);
        FILE* sec = _wfopen(cfg->secondary_dts, L"rb");
        if (sec) {
            char line[1024];
            while (fgets(line, sizeof(line), sec)) {
                fputs(line, out);
            }
            fclose(sec);
        }
        fputs("\n*/\n", out);
    }

    fclose(out);

    if (wcslen(cfg->dtc_exe) > 0 && wcslen(cfg->primary_dts) > 0) {
        int rc = run_dtc_compile_check(cfg->dtc_exe, target_dts, target_dtb);
        printf("[DTC] Compilation check exited with code %d\n", rc);
    }
    return 0;
}
